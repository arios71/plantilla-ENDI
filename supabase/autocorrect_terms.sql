-- Diccionario autocorrector de Auto-Linker.
-- Seguro para ejecutar sobre la tabla ya creada: no elimina tablas, datos ni políticas.
-- Las tres listas comparten la sesión de Supabase; solo el administrador puede escribir.

create table if not exists public.autocorrect_terms (
  id bigint generated by default as identity primary key,
  incorrect text not null,
  correction text not null,
  created_at timestamptz not null default now(),
  constraint autocorrect_terms_nonempty_incorrect check (length(trim(incorrect)) > 0),
  constraint autocorrect_terms_nonempty_correction check (length(trim(correction)) > 0)
);

create unique index if not exists autocorrect_terms_incorrect_ci_unique
  on public.autocorrect_terms (lower(trim(incorrect)));

alter table public.autocorrect_terms enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'autocorrect_terms' and policyname = 'Autocorrect terms are readable') then
    create policy "Autocorrect terms are readable" on public.autocorrect_terms for select to anon, authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'autocorrect_terms' and policyname = 'Only Auto-Linker admin can add autocorrect terms') then
    create policy "Only Auto-Linker admin can add autocorrect terms" on public.autocorrect_terms for insert to authenticated with check ((auth.jwt() ->> 'email') = 'arios71@gmail.com');
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'autocorrect_terms' and policyname = 'Only Auto-Linker admin can edit autocorrect terms') then
    create policy "Only Auto-Linker admin can edit autocorrect terms" on public.autocorrect_terms for update to authenticated using ((auth.jwt() ->> 'email') = 'arios71@gmail.com') with check ((auth.jwt() ->> 'email') = 'arios71@gmail.com');
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'autocorrect_terms' and policyname = 'Only Auto-Linker admin can delete autocorrect terms') then
    create policy "Only Auto-Linker admin can delete autocorrect terms" on public.autocorrect_terms for delete to authenticated using ((auth.jwt() ->> 'email') = 'arios71@gmail.com');
  end if;
end
$$;

grant select on public.autocorrect_terms to anon, authenticated;
grant insert, update, delete on public.autocorrect_terms to authenticated;

do $$
declare seq_name text;
begin
  seq_name := pg_get_serial_sequence('public.autocorrect_terms', 'id');
  if seq_name is not null then
    execute format('grant usage, select on sequence %s to authenticated', seq_name::regclass);
  end if;
end
$$;

