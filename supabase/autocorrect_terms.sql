-- Diccionario autocorrector de Auto-Linker.
-- Ejecutar una sola vez en Supabase > SQL Editor.
-- Esta tabla es independiente de dictionary_terms y anglicism_terms.

create table if not exists public.autocorrect_terms (
  id bigint generated by default as identity primary key,
  incorrect text not null,
  correction text not null,
  created_at timestamptz not null default now(),
  constraint autocorrect_terms_nonempty_incorrect check (length(trim(incorrect)) > 0),
  constraint autocorrect_terms_nonempty_correction check (length(trim(correction)) > 0)
);

create unique index if not exists autocorrect_terms_incorrect_ci_unique
  on public.autocorrect_terms (lower(trim(incorrect)));

alter table public.autocorrect_terms enable row level security;

drop policy if exists "Autocorrect terms are readable" on public.autocorrect_terms;
create policy "Autocorrect terms are readable"
  on public.autocorrect_terms
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Only Auto-Linker admin can add autocorrect terms" on public.autocorrect_terms;
create policy "Only Auto-Linker admin can add autocorrect terms"
  on public.autocorrect_terms
  for insert
  to authenticated
  with check ((auth.jwt() ->> 'email') = 'arios71@gmail.com');

drop policy if exists "Only Auto-Linker admin can delete autocorrect terms" on public.autocorrect_terms;
create policy "Only Auto-Linker admin can delete autocorrect terms"
  on public.autocorrect_terms
  for delete
  to authenticated
  using ((auth.jwt() ->> 'email') = 'arios71@gmail.com');

grant select on public.autocorrect_terms to anon, authenticated;
grant insert, delete on public.autocorrect_terms to authenticated;
grant usage, select on sequence public.autocorrect_terms_id_seq to authenticated;
